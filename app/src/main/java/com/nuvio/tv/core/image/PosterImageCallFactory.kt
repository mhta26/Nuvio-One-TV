package com.nuvio.tv.core.image

import okhttp3.Call
import okhttp3.OkHttpClient
import okhttp3.Request
import java.util.concurrent.TimeUnit

/** A generated poster may take longer than a static CDN image. Both clients share the same
 * dispatcher/connection pool and TV request budget; only the generating host gets more time.
 */
internal class PosterImageCallFactory(
    private val standard: OkHttpClient,
    private val isGenerator: (String) -> Boolean = { host ->
        host == "postersplus.cc" || host.endsWith(".postersplus.cc")
    }
) : Call.Factory {
    private val generated by lazy {
        standard.newBuilder()
            .readTimeout(25, TimeUnit.SECONDS).callTimeout(30, TimeUnit.SECONDS)
            .addInterceptor { chain ->
                val request = chain.request()
                chain.proceed(if (request.header("User-Agent") == null) {
                    request.newBuilder().header("User-Agent", "Nuvio One TV").build()
                } else request)
            }.build()
    }
    override fun newCall(request: Request): Call =
        (if (isGenerator(request.url.host)) generated else standard).newCall(request)
}
